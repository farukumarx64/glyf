import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'vite';
import schema from '../schema/mosaic-v0.1.schema.json' with { type: 'json' };
import { validatorOptions } from './validator-options.ts';

const ajv = new Ajv2020({ ...validatorOptions, code: { source: true, lines: true } });
const source = standaloneCode(ajv, ajv.compile(schema));
const target = new URL('../src/core/schema-validator.generated.js', import.meta.url);
const cache = new URL('../node_modules/.cache/mosaic/', import.meta.url);
await mkdir(cache, { recursive: true });
const scratch = await mkdtemp(path.join(fileURLToPath(cache), 'validator-'));

try {
  const entry = path.join(scratch, 'validator.cjs');
  await writeFile(entry, source);
  // Ajv's standalone output uses CommonJS runtime helpers even in its ESM mode.
  // Bundle the Unicode-length helper with the validator using the existing build
  // tool, producing a portable ESM module with no compiler or runtime imports.
  const result = await build({
    configFile: false,
    logLevel: 'silent',
    build: {
      write: false,
      minify: true,
      lib: { entry, formats: ['es'] },
      rolldownOptions: { output: { comments: false } },
    },
  });
  if (!Array.isArray(result) || result.length !== 1) {
    throw new Error('Expected one standalone validator build.');
  }
  const output = result[0]!.output;
  const chunk = output[0];
  if (
    output.length !== 1 ||
    chunk?.type !== 'chunk' ||
    chunk.imports.length ||
    chunk.dynamicImports.length ||
    !chunk.exports.includes('default')
  ) {
    throw new Error('Expected a self-contained validator with a default export.');
  }
  const generated = '// Generated by npm run generate:validator. Do not edit.\n' + chunk.code;
  const previous = await readFile(target, 'utf8').catch((error: NodeJS.ErrnoException) => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  // Avoid unnecessary dev-server reloads when the schema and compiler are unchanged.
  if (previous !== generated) await writeFile(target, generated);
  console.log('Generated the standalone Mosaic schema validator.');
} finally {
  await rm(scratch, { recursive: true, force: true });
}
